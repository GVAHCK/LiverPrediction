    d = load_json("12_statistics.json")
    prim = d["primary_comparison"]
    sec = d["secondary_comparisons"]
    l03 = d["leakage_gap_bootstrap"]

    rows = []
    d_prim = prim["mean_diff_worst_miss"] * 100
