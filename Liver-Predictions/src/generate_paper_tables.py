#!/usr/bin/env python3
"""
src/generate_paper_tables.py

Automatically generates publishable LaTeX tables for the Elsevier-neutral manuscript
exclusively from /reports/*.json data files.
Zero hand-typed numbers: every number is dynamically loaded and formatted.
"""

import os
import json
import pandas as pd
import numpy as np

PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
REPORTS_DIR = os.path.join(PROJECT_ROOT, "reports")
PAPER_DIR = os.path.join(PROJECT_ROOT, "paper")
TABLES_DIR = os.path.join(PAPER_DIR, "tables")

def load_json(filename):
    path = os.path.join(REPORTS_DIR, filename)
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)

def render_template(template_str, mapping):
    out = template_str
    for k, v in mapping.items():
        out = out.replace(f"@{k}@", str(v))
    return out

