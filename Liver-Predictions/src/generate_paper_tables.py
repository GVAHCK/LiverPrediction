    rows.append(f"\\textbf{{Primary: Sex-Audited vs Global Confidence ($B=0.20$)}} & {d_prim:+.2f}\\% & [{ci_p_low:.2f}\\%, {ci_p_high:.2f}\\%] & {p_prim:.4f} & {p_prim:.4f} & Prespecified (Fail to reject $H_0$) \\\\")

